#!/usr/bin/env python3
"""Bake the existing DejaVu Sans into a compact 2-bit boot font (Pillow required).
Normal builds use the committed atlas and need no Python imaging packages.
"""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[1]
font=ImageFont.truetype(str(root/'fonts/DejaVuSans.ttf'),16)
data=[];glyphs=[]
for code in range(32,127):
 ch=chr(code);x0,y0,x1,y1=font.getbbox(ch,anchor='ls');w,h=x1-x0,y1-y0
 im=Image.new('L',(max(w,1),max(h,1)));ImageDraw.Draw(im).text((-x0,-y0),ch,font=font,fill=255,anchor='ls')
 values=[min(3,(p+42)//85) for p in im.tobytes()[:w*h]]
 glyphs.append((len(data),w,h,x0,y0,round(font.getlength(ch))))
 for i in range(0,len(values),4):data.append(sum(v<<(2*j) for j,v in enumerate(values[i:i+4])))
out=['/* Generated by tools/build_boot_font.py from fonts/DejaVuSans.ttf.',' * DejaVu font license: fonts/LICENSE. 16px, proportional, four coverage levels. */', '#ifndef BOOT_FONT_H','#define BOOT_FONT_H','typedef struct { unsigned short offset; unsigned char w,h; signed char x,y; unsigned char advance; } boot_glyph_t;', 'static const boot_glyph_t boot_glyphs[95] = {']
out += ['{'+','.join(map(str,g))+'},' for g in glyphs];out+=['};','static const unsigned char boot_font_bits[] = {']
for i in range(0,len(data),24):out.append(','.join(map(str,data[i:i+24]))+',')
out+=['};']
word_font=ImageFont.truetype(str(root/'fonts/DejaVuSans.ttf'),32)
box=word_font.getbbox('Banana OS',anchor='lt');word=Image.new('L',(box[2],box[3]))
ImageDraw.Draw(word).text((0,0),'Banana OS',font=word_font,fill=255,anchor='lt')
values=[min(3,(v+42)//85) for v in word.tobytes()]
packed=[sum(v<<(2*j) for j,v in enumerate(values[i:i+4])) for i in range(0,len(values),4)]
out += [f'#define BOOT_WORDMARK_W {word.width}',f'#define BOOT_WORDMARK_H {word.height}','static const unsigned char boot_wordmark_bits[] = {']
for i in range(0,len(packed),24):out.append(','.join(map(str,packed[i:i+24]))+',')
out+=['};','#endif'];(root/'loader/boot_font.h').write_text('\n'.join(out)+'\n');print('Boot font:',len(data),'bitmap bytes,',len(glyphs),'glyphs')
