#!/usr/bin/env python3
"""Regenerate the matching host and kernel vector layouts (no SIMD ABI)."""
from pathlib import Path
import json
root = Path(__file__).resolve().parent
widths = (2, 3, 4, 8, 16)
kernel = ['/* generated by gen-clvectors.py */']
host = ['/* Generated by sdk/lib/gen-clvectors.py. Three lanes have four-lane size. */', '#ifndef BANANA_CL_VECTORS_H', '#define BANANA_CL_VECTORS_H']
for base in ('float', 'int', 'uint'):
    for n in widths:
        padded = 4 if n == 3 else n
        fields = ' '.join(f'{base} s{i:x};' for i in range(padded))
        xyzw = 'struct { ' + ' '.join(f'{base} {x};' for x in 'xyzw'[:n]) + ' };' if n <= 4 else ''
        body = f'{base} s[{padded}]; struct {{ {fields} }}; {xyzw}'
        kernel.append(f'typedef union __bcl_vec_{base}{n} {{ {body} }} __attribute__((aligned({padded*4}))) {base}{n};')
        hostbody = body.replace(base, 'cl_' + base)
        host.append(f'typedef union {{ {hostbody} }} __attribute__((aligned({padded*4}))) cl_{base}{n};')
        kernel += [f'static {base}{n} __bcl_load_{base}{n}(size_t offset,const {base}* p) {{ {base}{n} r; int i; for(i=0;i<{n};i++) r.s[i]=p[offset*{n}+i]; return r; }}',
                   f'static void __bcl_store_{base}{n}({base}{n} v,size_t offset,{base}* p) {{ int i; for(i=0;i<{n};i++) p[offset*{n}+i]=v.s[i]; }}']
for n in widths:
    for name, expr in [('sqrt','sqrt(a.s[i])'), ('sin','sin(a.s[i])'), ('cos','cos(a.s[i])'), ('fabs','fabs(a.s[i])')]:
        kernel.append(f'static float{n} __bcl_{name}_float{n}(float{n} a) {{ float{n} r; int i; for(i=0;i<{n};i++) r.s[i]={expr}; return r; }}')
    for base in ('float','int','uint'):
        for name, sign in [('min','<'),('max','>')]:
            kernel.append(f'static {base}{n} __bcl_{name}_{base}{n}({base}{n} a,{base}{n} b) {{ {base}{n} r; int i; for(i=0;i<{n};i++) r.s[i]=a.s[i]{sign}b.s[i]?a.s[i]:b.s[i]; return r; }}')
    kernel.append(f'static float __bcl_dot_float{n}(float{n} a,float{n} b) {{ float r=0; int i; for(i=0;i<{n};i++) r+=a.s[i]*b.s[i]; return r; }}')
    kernel.append(f'static float __bcl_length_float{n}(float{n} a) {{ return sqrt(__bcl_dot_float{n}(a,a)); }}')
    kernel.append(f'static float{n} __bcl_normalize_float{n}(float{n} a) {{ float d=__bcl_length_float{n}(a); return a/d; }}')
# Scalar overloads preserve integer widths in min/max (including size_t).
for base in ('float','double','int','unsigned int','long','unsigned long','long long','unsigned long long'):
    suffix=base.replace(' ','_')
    for name, sign in [('min','<'),('max','>')]:
        kernel.append(f'static {base} __bcl_{name}_{suffix}({base} a,{base} b) {{ return a{sign}b?a:b; }}')
for n in widths:
    opts=','.join(f'{base}*:__bcl_load_{base}{n},const {base}*:__bcl_load_{base}{n}' for base in ('float','int','uint'))
    kernel.append(f'#define vload{n}(o,p) _Generic((p),{opts})((o),(p))')
    opts=','.join(f'{base}{n}:__bcl_store_{base}{n}' for base in ('float','int','uint'))
    kernel.append(f'#define vstore{n}(v,o,p) _Generic((v),{opts})((v),(o),(p))')
for name in ('sqrt','sin','cos','fabs','dot','length','normalize','min','max'):
    kernel.append(f'#undef {name}')
    bases=('float','int','uint') if name in ('min','max') else ('float',)
    opts=[f'{base}{n}:__bcl_{name}_{base}{n}' for base in bases for n in widths]
    if name in ('min','max'):
        opts += [f'{base}:__bcl_{name}_{base.replace(" ","_")}' for base in ('float','double','int','unsigned int','long','unsigned long','long long','unsigned long long')]
    else:
        opts += [f'default:{name}'] if name in ('sqrt','sin','cos','fabs') else []
    args='a,b' if name in ('dot','min','max') else 'a'
    controlling='(a)+(b)' if name in ('min','max') else '(a)'
    kernel.append(f'#define {name}({args}) _Generic(({controlling}),'+','.join(opts)+')('+args+')')
kernel.append('#line 1 "program.cl"')
(root/'clvector-prelude.h').write_text('/* Generated by gen-clvectors.py. */\nstatic const char* VECTOR_PRELUDE =\n'+'\n'.join('    '+json.dumps(x+'\n') for x in kernel)+';\n')
host += ['#endif']
(root.parent/'include/CL/cl_vectors.h').write_text('\n'.join(host)+'\n')
