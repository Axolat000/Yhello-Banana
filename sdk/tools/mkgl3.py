"""mkgl3.py GLCOREARB_H OUT_H - the function list of <GL/gl3.h>.

Reads Khronos's glcorearb.h and writes OUT_H (sdk/include/GL/gl3procs.h):
every OpenGL function of versions 1.0 to 3.3 (core profile) as an X-macro
list, BGL3_PROCS(X) with X(type, name), and #define glName bgl3_glName for
each, so that apps call through the pointers bgl3 loads from Mesa."""
import re, sys

src = open(sys.argv[1]).read()
names = []
for m in re.finditer(r"#ifndef GL_VERSION_(\d)_(\d)\n(.*?)#endif /\* GL_VERSION_\1_\2 \*/", src, re.S):
    major, minor = int(m.group(1)), int(m.group(2))
    if (major, minor) > (3, 3):
        continue
    names += re.findall(r"GLAPI [^;]*?APIENTRY (gl\w+) \(", m.group(3))
seen, procs = set(), []
for n in names:
    if n not in seen:
        seen.add(n)
        procs.append(n)
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by sdk/tools/mkgl3.py from glcorearb.h: the OpenGL 1.0 - 3.3\n"
            " * core functions (%d). Do not edit. */\n" % len(procs))
    f.write("#ifndef BGL3_PROCS_H\n#define BGL3_PROCS_H\n\n#define BGL3_PROCS(X) \\\n")
    f.write(" \\\n".join("    X(PFN%sPROC, %s)" % (n.upper(), n) for n in procs))
    f.write("\n\n")
    for n in procs:
        f.write("#define %s bgl3_%s\n" % (n, n))
    f.write("\n#endif\n")
print(len(procs), "functions")
